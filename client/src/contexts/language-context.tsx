const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [language, setLanguage] = useState<Language>(() => {
    // SSR 환경에서는 기본값 반환
    if (typeof window === 'undefined') {
      return 'en';
    }

    // 초기값을 결정하는 함수
    try {
      // localStorage에서 언어 가져오기
      const savedLanguage = localStorage.getItem('language') as Language;

      // 유효한 언어인지 확인
      if (savedLanguage && Object.keys(translations).includes(savedLanguage)) {
        console.log('🌍 Using saved language preference:', savedLanguage);
        // Mark language as selected to skip language selection screen
        localStorage.setItem('language-selected', 'true');
        return savedLanguage;
      }

      // 브라우저 언어 감지
      const browserLang = navigator.language.toLowerCase();
      console.log('🌍 Detecting browser language:', browserLang);

      let detectedLang: Language = 'en';
      if (browserLang.startsWith('ko')) detectedLang = 'ko';
      else if (browserLang.startsWith('ja')) detectedLang = 'ja';
      else if (browserLang.startsWith('zh')) detectedLang = 'zh';

      // Save detected language and mark as selected
      localStorage.setItem('language', detectedLang);
      localStorage.setItem('language-selected', 'true');

      return detectedLang;
    } catch (error) {
      console.error('Language initialization error:', error);
      return 'en'; // 에러 발생 시 영어로 기본 설정
    }
  });

  const handleSetLanguage = (lang: Language) => {
    setLanguage(lang);
    // Only access localStorage in browser environment
    if (typeof window !== 'undefined') {
      localStorage.setItem('language', lang);
    }
  };

  // Update HTML lang attribute when language changes
  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = language;
    }
  }, [language]);

  const t = (key: string, variables?: Record<string, string | number>): string => {
    const currentTranslations = translations[language] as Record<string, string>;
    const fallbackTranslations = translations.en as Record<string, string>;
    let text = currentTranslations[key] || fallbackTranslations[key] || key;

    // Replace variables like {hours} with actual values
    if (variables) {
      Object.entries(variables).forEach(([varKey, varValue]) => {
        text = text.replace(`{${varKey}}`, String(varValue));
      });
    }

    return text;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage: handleSetLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};